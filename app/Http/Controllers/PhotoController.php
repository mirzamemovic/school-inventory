<?php

namespace App\Http\Controllers;

use App\Services\PhotoStorage;
use Illuminate\Http\Response;
use Symfony\Component\HttpKernel\Exception\NotFoundHttpException;

/**
 * Photos live outside the webroot and are served from here, so an uploads
 * directory can never execute PHP on shared hosting (spec section 13).
 *
 * Asset photos are public: the scan page shows them. Photos sent with a report
 * are not — only the director ever looks at them, and one taken in a
 * classroom can easily show a student.
 */
class PhotoController extends Controller
{
    public function __invoke(string $path, PhotoStorage $photos): Response
    {
        // Paths are generated by us and always look like `assets/<random>.jpg`.
        if (! preg_match('#^[a-z]+/[A-Za-z0-9]{40}\.jpg$#', $path) || ! $photos->exists($path)) {
            throw new NotFoundHttpException;
        }

        // Not found rather than forbidden: say nothing about whether it exists.
        if (! str_starts_with($path, 'assets/') && ! auth()->check()) {
            throw new NotFoundHttpException;
        }

        return response($photos->read($path), 200, [
            'Content-Type' => 'image/jpeg',
            'Cache-Control' => 'private, max-age=604800',
            'X-Content-Type-Options' => 'nosniff',
        ]);
    }
}
